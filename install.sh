#!/usr/bin/env bash
set -euo pipefail

sbx_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
envs_dir="$sbx_dir/envs"
doppler_project=""
doppler_config=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --envs-dir)
      envs_dir="$2"
      shift 2
      ;;
    --doppler-project)
      doppler_project="$2"
      shift 2
      ;;
    --doppler-config)
      doppler_config="$2"
      shift 2
      ;;
    *)
      echo "Error: unknown argument: $1" >&2
      exit 1
      ;;
  esac
done

# Validate environment directory
if [[ ! -d "$envs_dir" ]]; then
  echo "Error: no such directory: $envs_dir" >&2
  exit 1
fi

envs_dir="$(cd "$envs_dir" && pwd)"

if [[ ! -f "$envs_dir/00-base.yaml" ]]; then
  echo "Error: $envs_dir/00-base.yaml not found" >&2
  exit 1
fi

if [[ ! -d "$envs_dir/agents" ]]; then
  echo "Error: $envs_dir/agents directory not found" >&2
  exit 1
fi

# Validate Doppler defaults
if [[ ( -n "$doppler_project" && -z "$doppler_config" ) ||
      ( -z "$doppler_project" && -n "$doppler_config" ) ]]; then
  echo "Error: pass both --doppler-project and --doppler-config, or neither" >&2
  exit 1
fi

# Generate launcher
bin_dir="$HOME/.local/bin"
mkdir -p "$bin_dir"

target="$bin_dir/aibox"

# Safely embed the absolute environment directory
printf -v quoted_envs_dir '%q' "$envs_dir"

cat > "$target" <<EOF
#!/usr/bin/env bash
set -euo pipefail

# Generated by $sbx_dir/install.sh
# Re-run install.sh if the environment directory moves.

envs_dir=$quoted_envs_dir
EOF

cat >> "$target" <<'EOF'

config_file="${XDG_CONFIG_HOME:-$HOME/.config}/aibox/config.yaml"

# Discover available agents
available_agents() {
  local file
  local agents=()

  shopt -s nullglob

  for file in "$envs_dir"/agents/*.yaml; do
    agents+=("$(basename "$file" .yaml)")
  done

  shopt -u nullglob

  if [[ ${#agents[@]} -eq 0 ]]; then
    echo "none found"
  else
    printf '%s ' "${agents[@]}"
    echo
  fi
}

usage() {
  echo "Usage: $(basename "$0") <agent> [--doppler-project <project>] [--doppler-config <config>] [sbx env run args...]" >&2
  echo "Falls back to $config_file for Doppler defaults." >&2
  echo "Available agents: $(available_agents)" >&2
}

# Agent selection
agent="${1:-}"

if [[ -z "$agent" ]]; then
  usage
  exit 1
fi

shift

agent_file="$envs_dir/agents/$agent.yaml"

if [[ ! -f "$agent_file" ]]; then
  echo "Error: no agent configuration: $agent_file" >&2
  usage
  exit 1
fi

# Parse Doppler arguments
doppler_project=""
doppler_config=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --doppler-project)
      doppler_project="$2"
      shift 2
      ;;
    --doppler-config)
      doppler_config="$2"
      shift 2
      ;;
    *)
      break
      ;;
  esac
done

# Read per-user defaults
config_value() {
  local key="$1"

  [[ -f "$config_file" ]] || return 0

  awk -F': *' -v k="$key" \
    '$1==k {print $2; exit}' "$config_file"
}

[[ -n "$doppler_project" ]] ||
  doppler_project="$(config_value doppler_project)"

[[ -n "$doppler_config" ]] ||
  doppler_config="$(config_value doppler_config)"

if [[ -z "$doppler_project" || -z "$doppler_config" ]]; then
  echo "Error: Doppler project and config are required." >&2
  usage
  exit 1
fi

# Discover shared environment files
# Bash expands *.yaml alphabetically.
# Only top-level files are included.
shared_envs=()

shopt -s nullglob

for file in "$envs_dir"/*.yaml; do
  shared_envs+=("$file")
done

shopt -u nullglob

if [[ ${#shared_envs[@]} -eq 0 ]]; then
  echo "Error: no shared environment files found." >&2
  exit 1
fi

# Load shared environments first, agent overlay last
exec sbx env run \
  "${shared_envs[@]}" \
  "$agent_file" \
  --env-arg workspace="$PWD" \
  --env-arg doppler_project="$doppler_project" \
  --env-arg doppler_config="$doppler_config" \
  "$@"
EOF

chmod +x "$target"

echo "Installed $target"
echo "Environment directory: $envs_dir"
echo "Agents: $(find "$envs_dir/agents" -maxdepth 1 -type f -name '*.yaml' -exec basename {} .yaml \; | sort | tr '\n' ' ')"

# Optionally save Doppler defaults
if [[ -n "$doppler_project" ]]; then
  config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/aibox"
  mkdir -p "$config_dir"

  cat > "$config_dir/config.yaml" <<CFG
doppler_project: $doppler_project
doppler_config: $doppler_config
CFG

  chmod 600 "$config_dir/config.yaml"
  echo "Wrote $config_dir/config.yaml"
fi
